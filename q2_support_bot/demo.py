"""Run a scripted 12-turn conversation and save it to demo_transcript.md."""
from pathlib import Path

from bot import SupportBot

TURNS = [
    ("Start", "Hi, I'm filling in my HDFC Life forms. What is the NACH mandate form for?"),
    ("Follow-up", "Which debit frequency options does it offer?"),
    ("Follow-up", "What happens if the debit fails because there isn't enough money in my account?"),
    ("Topic switch", "Different question - what is the FATCA annexure form and why do I need it?"),
    ("Follow-up", "Which documents do I have to submit with it?"),
    ("Repeat question", "Sorry, what did you say the NACH form is for again?"),
    ("Topic switch", "Now about the Moral Hazard Questionnaire: when do I need to fill it in?"),
    ("Follow-up", "Will a nominee relationship written as 'others' be accepted?"),
    ("Topic switch", "What does assigning my policy mean, and does it affect my nominee?"),
    ("Back-reference", "Going back to the mandate form - can I cancel it later?"),
    ("Topic switch", "What am I confirming when I sign the Benefit Illustration declaration?"),
    ("Memory", "Can you list which forms we have discussed so far in this chat?"),
]


def main():
    bot = SupportBot()
    lines = ["# Q2 Demo Transcript (12 turns)", "",
             "Generated by `python demo.py` with the local model. Each turn shows the user's message, what the "
             "turn is testing, the standalone search query the bot built from the conversation, and the reply "
             "with its section citation.", ""]
    for i, (kind, question) in enumerate(TURNS, 1):
        r = bot.ask(question)
        print(f"\n[{i}] {kind}: {question}\n{r['answer']}")
        lines += [f"## Turn {i} - {kind}", "",
                  f"**User:** {question}", "",
                  f"*Search query used:* `{r['query']}`", "",
                  f"**Assistant:** {r['answer']}", ""]
    out = Path(__file__).parent / "demo_transcript.md"
    out.write_text("\n".join(lines))
    print(f"\nSaved {out}")


if __name__ == "__main__":
    main()
